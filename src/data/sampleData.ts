export function pickAutoReplies(userText: string): string[] {
  const lower = userText.toLowerCase();
  if (lower.includes('car') || lower.includes('van') || lower.includes('bus') || lower.includes('drive') || lower.includes('transport') || lower.includes('sgr')) {
    return [AUTO_REPLY_POOLS.transport[0], AUTO_REPLY_POOLS.meeting[0]];
  }
  if (lower.includes('pay') || lower.includes('mpesa') || lower.includes('budget') || lower.includes('kes') || lower.includes('money') || lower.includes('cost')) {
    return [AUTO_REPLY_POOLS.budget[0], AUTO_REPLY_POOLS.budget[1]];
  }
  if (lower.includes('meet') || lower.includes('time') || lower.includes('8am') || lower.includes('where') || lower.includes('location')) {
    return [AUTO_REPLY_POOLS.meeting[0], AUTO_REPLY_POOLS.transport[1]];
  }
  const idx = Math.floor(Math.random() * AUTO_REPLY_POOLS.general.length);
  const idx2 = (idx + 1) % AUTO_REPLY_POOLS.general.length;
  return [AUTO_REPLY_POOLS.general[idx], AUTO_REPLY_POOLS.general[idx2]];
}

export function formatKES(amount: number): string {
  return `KES ${Math.round(amount).toLocaleString('en-KE')}`;
}

export function formatDateShort(dateStr: string): string {
  try {
    const d = new Date(dateStr + 'T00:00:00');
    return d.toLocaleDateString('en-KE', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
    });
  } catch {
    return dateStr;
  }
}
